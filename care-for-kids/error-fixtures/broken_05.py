# Storage conversions.

def bytes_to_bits(value: float) -> float:
    """Convert bytes to bits.

    Accepts fractional values and preserves the sign.
    """
    result = value * 8.0
    return result


def bits_to_bytes(value: float) -> float:
    """Convert bits to bytes.

    Accepts fractional values and preserves the sign.
    """
    result = value / 8.0
    return result


